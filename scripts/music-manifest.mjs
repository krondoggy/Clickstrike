import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const MUSIC_DIRECTORY = fileURLToPath(new URL('../assets/audio/music/', import.meta.url));
const AUDIO_EXTENSION = /\.(mp3|ogg|wav|m4a|aac|flac|opus|webm)$/i;

export async function scanMusicFiles(directory = MUSIC_DIRECTORY) {
  const entries = await readdir(directory, { withFileTypes: true });
  return entries
    .filter(entry => entry.isFile() && AUDIO_EXTENSION.test(entry.name))
    .map(entry => entry.name)
    .sort();
}

export function musicPlaylistModule(files) {
  return `// Generated by npm run music:refresh. Add audio files to this folder, then regenerate.\nexport default ${JSON.stringify(files, null, 2)};\n`;
}

export async function generateMusicPlaylist(directory = MUSIC_DIRECTORY) {
  const files = await scanMusicFiles(directory);
  await writeFile(path.join(directory, 'playlist.js'), musicPlaylistModule(files));
  return files;
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const files = await generateMusicPlaylist();
  console.log(`Music playlist updated: ${files.length} tracks.`);
}
